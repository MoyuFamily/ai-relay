#!/usr/bin/env bash
# ============================================================
# AI Relay — One-Command Self-Hosted Quick Start (Docker)
# ============================================================
# Generates a secure RELAY_API_KEY into .env (if absent) and
# launches AI Relay via Docker Compose.
#
# Usage:
#   bash scripts/quick-start.sh            # Single-container disk mode
#   bash scripts/quick-start.sh --postgres # Multi-instance PostgreSQL mode
# ============================================================

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

USE_POSTGRES=false
for arg in "$@"; do
  case "$arg" in
    --postgres) USE_POSTGRES=true ;;
    -h|--help)
      echo "Usage: $0 [--postgres]"
      echo "  (default)   Single-container persistent disk mode (./data/kv-store.json)"
      echo "  --postgres  Start with bundled PostgreSQL container"
      exit 0
      ;;
    *)
      echo "Unknown option: $arg" >&2
      exit 1
      ;;
  esac
done

if ! command -v docker >/dev/null 2>&1; then
  echo "❌ Docker is not installed. Install Docker first: https://docs.docker.com/get-docker/" >&2
  exit 1
fi

generate_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  elif command -v node >/dev/null 2>&1; then
    node -e "console.log(require('crypto').randomBytes(24).toString('hex'))"
  else
    date +%s%N | sha256sum | cut -c1-48
  fi
}

if [ ! -f .env ]; then
  API_KEY="$(generate_secret)"
  cat > .env <<EOF
# Generated by scripts/quick-start.sh
RELAY_API_KEY=${API_KEY}
PORT=3000
EOF
  if [ "$USE_POSTGRES" = true ]; then
    PG_PASS="$(generate_secret)"
    cat >> .env <<EOF
POSTGRES_USER=airelay
POSTGRES_PASSWORD=${PG_PASS}
POSTGRES_DB=airelay
DATABASE_URL=postgresql://airelay:${PG_PASS}@postgres:5432/airelay
EOF
  fi
  chmod 600 .env
  echo "✅ Created .env with a randomly generated RELAY_API_KEY."
else
  echo "ℹ️  Using existing .env file."
  if [ "$USE_POSTGRES" = true ] && ! grep -q '^DATABASE_URL=' .env; then
    PG_PASS="$(generate_secret)"
    cat >> .env <<EOF
POSTGRES_USER=airelay
POSTGRES_PASSWORD=${PG_PASS}
POSTGRES_DB=airelay
DATABASE_URL=postgresql://airelay:${PG_PASS}@postgres:5432/airelay
EOF
    echo "✅ Appended PostgreSQL configuration to .env."
  fi
fi

PORT_VAL="$(grep -E '^PORT=' .env | tail -1 | cut -d'=' -f2- | tr -d '"' || true)"
PORT_VAL="${PORT_VAL:-3000}"
KEY_VAL="$(grep -E '^RELAY_API_KEY=' .env | tail -1 | cut -d'=' -f2- | tr -d '"' || true)"

echo "🚀 Starting AI Relay..."
if [ "$USE_POSTGRES" = true ]; then
  docker compose --profile postgres up -d --build
else
  docker compose up -d --build
fi

echo ""
echo "════════════════════════════════════════════════════"
echo "✅ AI Relay is starting up!"
echo "   Admin UI : http://localhost:${PORT_VAL}/admin"
echo "   Health   : http://localhost:${PORT_VAL}/health?liveness=1"
echo "   API Base : http://localhost:${PORT_VAL}/v1"
if [ -n "$KEY_VAL" ]; then
  echo "   API Key  : ${KEY_VAL}"
fi
echo ""
echo "👉 Open /admin with the API Key above to add your upstream provider keys."
echo "════════════════════════════════════════════════════"
